            "def impute_subset(df_sub, limit=2):\n",
            "    res = []\n",
            "    for pid, grp in df_sub.groupby(\"MaDiemDo\"):\n",
            "        grp = grp.set_index(\"TIME\").sort_index().copy()\n",
            "        present = [c for c in NUMERIC_COLS if c in grp.columns]\n",
            "        was_null = grp[\"P_kW\"].isna()\n",
            "        imp = grp[present].interpolate(method=\"time\", limit=limit, limit_direction=\"forward\")\n",
            "        grp[present] = imp\n",
            "        grp[\"is_imputed\"] = (was_null & imp[\"P_kW\"].notna()).astype(int)\n",
            "        res.append(grp.reset_index())\n",
