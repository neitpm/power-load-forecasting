            "def parse_time_robust(df):\n",
            "    time_col = next((c for c in [\"TIME\", \"Time\", \"ThoiGian\", \"THOIGIAN\", \"Gio\"] if c in df.columns), None)\n",
            "    if not time_col:\n",
            "        return pd.Series([pd.NaT] * len(df))\n",
            "    s_time = df[time_col].astype(str).str.strip()\n",
            "    has_year = s_time.str.contains(r\"\\b202[0-5]\\b\", regex=True)\n",
            "    \n",
            "    date_col = next((c for c in [\"DATE\", \"Date\", \"Ngay\", \"NGAY\"] if c in df.columns), None)\n",
            "    if date_col:\n",
            "        s_date = pd.to_datetime(df[date_col], errors=\"coerce\", format=\"mixed\")\n",
            "        s_fixed = s_time.str.replace(r\"\\s+\", \"\", regex=True)\n",
            "        s_fixed = s_fixed.where(s_fixed.str.count(\":\") == 2, \"00:\" + s_fixed)\n",
